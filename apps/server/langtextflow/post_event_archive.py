"""Private post-event archive storage. Audio lives on disk, metadata in SQLite."""
from __future__ import annotations

import sqlite3
from datetime import UTC, datetime
from pathlib import Path
from uuid import uuid4


def _now() -> str:
    return datetime.now(UTC).isoformat()


class PostEventArchive:
    """Session-linked recordings and immutable summary attempts."""

    def __init__(self, database_path: str) -> None:
        self.database_path = Path(database_path)
        self.audio_root = self.database_path.parent / "recordings"

    def _connect(self) -> sqlite3.Connection:
        conn = sqlite3.connect(self.database_path, timeout=5)
        conn.row_factory = sqlite3.Row
        conn.execute("PRAGMA foreign_keys=ON")
        return conn

    def initialize(self) -> None:
        self.audio_root.mkdir(parents=True, exist_ok=True)
        with self._connect() as conn:
            conn.execute(
                """
                CREATE TABLE IF NOT EXISTS session_recordings (
                    recording_id TEXT PRIMARY KEY,
                    session_id TEXT NOT NULL,
                    filename TEXT NOT NULL UNIQUE,
                    media_type TEXT NOT NULL,
                    size_bytes INTEGER NOT NULL CHECK(size_bytes >= 0),
                    sha256 TEXT NOT NULL,
                    duration_seconds REAL NOT NULL CHECK(duration_seconds >= 0),
                    sample_rate INTEGER NOT NULL CHECK(sample_rate > 0),
                    channels INTEGER NOT NULL CHECK(channels IN (1,2)),
                    created_at TEXT NOT NULL,
                    FOREIGN KEY(session_id) REFERENCES sessions(session_id) ON DELETE CASCADE
                )
                """
            )
            conn.execute(
                """
                CREATE TABLE IF NOT EXISTS session_summaries (
                    summary_id TEXT PRIMARY KEY,
                    session_id TEXT NOT NULL,
                    language TEXT NOT NULL,
                    provider TEXT NOT NULL,
                    model TEXT NOT NULL,
                    transcript_sha256 TEXT NOT NULL,
                    prompt_version TEXT NOT NULL,
                    status TEXT NOT NULL CHECK(status IN ('running','completed','error')),
                    content TEXT NOT NULL DEFAULT '',
                    error TEXT,
                    created_at TEXT NOT NULL,
                    updated_at TEXT NOT NULL,
                    FOREIGN KEY(session_id) REFERENCES sessions(session_id) ON DELETE CASCADE
                )
                """
            )
            conn.execute(
                "CREATE INDEX IF NOT EXISTS idx_session_recordings "
                "ON session_recordings(session_id, created_at)"
            )
            conn.execute(
                "CREATE INDEX IF NOT EXISTS idx_session_summaries "
                "ON session_summaries(session_id, created_at DESC)"
            )
            # Background tasks cannot survive process termination.
            conn.execute(
                "UPDATE session_summaries SET status='error', "
                "error='Generation interrupted by application restart', updated_at=? "
                "WHERE status='running'",
                (_now(),),
            )

    def insert_recording(
        self,
        session_id: str,
        *,
        filename: str,
        size_bytes: int,
        sha256: str,
        duration_seconds: float,
        sample_rate: int,
        channels: int,
    ) -> dict:
        # File names are generated by this service and cannot be supplied by a caller.
        if Path(filename).name != filename or not filename.endswith(".wav"):
            raise ValueError("invalid recording filename")
        recording_id = str(uuid4())
        created_at = _now()
        with self._connect() as conn:
            conn.execute(
                """
                INSERT INTO session_recordings
                  (recording_id, session_id, filename, media_type, size_bytes,
                   sha256, duration_seconds, sample_rate, channels, created_at)
                VALUES (?, ?, ?, 'audio/wav', ?, ?, ?, ?, ?, ?)
                """,
                (
                    recording_id, session_id, filename, size_bytes, sha256,
                    duration_seconds, sample_rate, channels, created_at,
                ),
            )
        return {
            "recording_id": recording_id,
            "session_id": session_id,
            "media_type": "audio/wav",
            "size_bytes": size_bytes,
            "sha256": sha256,
            "duration_seconds": duration_seconds,
            "sample_rate": sample_rate,
            "channels": channels,
            "created_at": created_at,
        }

    def recordings(self, session_id: str) -> list[dict]:
        with self._connect() as conn:
            rows = conn.execute(
                "SELECT recording_id, session_id, media_type, size_bytes, sha256, "
                "duration_seconds, sample_rate, channels, created_at "
                "FROM session_recordings WHERE session_id=? ORDER BY created_at",
                (session_id,),
            ).fetchall()
        return [dict(row) for row in rows]

    def recording_path(self, session_id: str, recording_id: str) -> Path | None:
        with self._connect() as conn:
            row = conn.execute(
                "SELECT filename FROM session_recordings "
                "WHERE session_id=? AND recording_id=?",
                (session_id, recording_id),
            ).fetchone()
        if row is None:
            return None
        name = str(row["filename"])
        if Path(name).name != name or not name.endswith(".wav"):
            return None
        root = self.audio_root.resolve()
        candidate = root / name
        # Check the raw entry before resolving; Path.resolve() follows symlinks.
        # A link to another managed recording must not bypass session ownership.
        if candidate.is_symlink():
            return None
        resolved = candidate.resolve()
        if resolved.parent != root or not resolved.is_file():
            return None
        return resolved

    def recording_paths_for_session(self, session_id: str) -> list[Path]:
        with self._connect() as conn:
            ids = [
                str(row[0]) for row in conn.execute(
                    "SELECT recording_id FROM session_recordings WHERE session_id=?",
                    (session_id,),
                )
            ]
        return [path for item in ids if (path := self.recording_path(session_id, item))]

    def begin_summary(
        self, session_id: str, *, language: str, provider: str,
        model: str, transcript_sha256: str, prompt_version: str,
    ) -> dict:
        summary_id = str(uuid4())
        stamp = _now()
        with self._connect() as conn:
            conn.execute(
                """
                INSERT INTO session_summaries
                  (summary_id, session_id, language, provider, model, transcript_sha256,
                   prompt_version, status, content, created_at, updated_at)
                VALUES (?, ?, ?, ?, ?, ?, ?, 'running', '', ?, ?)
                """,
                (
                    summary_id, session_id, language, provider, model,
                    transcript_sha256, prompt_version, stamp, stamp,
                ),
            )
        return self.summary_by_id(summary_id)

    def finish_summary(
        self, summary_id: str, *, content: str = "", error: str | None = None
    ) -> None:
        with self._connect() as conn:
            conn.execute(
                "UPDATE session_summaries SET status=?, content=?, error=?, updated_at=? "
                "WHERE summary_id=? AND status='running'",
                ("error" if error else "completed", content, error, _now(), summary_id),
            )

    def summary_by_id(self, summary_id: str) -> dict | None:
        with self._connect() as conn:
            row = conn.execute(
                "SELECT * FROM session_summaries WHERE summary_id=?", (summary_id,),
            ).fetchone()
        return dict(row) if row else None

    def latest_summary(self, session_id: str) -> dict | None:
        with self._connect() as conn:
            row = conn.execute(
                "SELECT * FROM session_summaries WHERE session_id=? "
                "ORDER BY created_at DESC, rowid DESC LIMIT 1",
                (session_id,),
            ).fetchone()
        return dict(row) if row else None
